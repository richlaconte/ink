// Turn data/json/*.json + data/metrics/*.woff2 into one ES module per hand.
// Each module carries the glyph centrelines and its metrics font inlined as a
// data URI, so the package needs no bundler asset configuration.
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const out = new URL('src/hands/', root);
mkdirSync(out, { recursive: true });

const LICENSE = {
  hershey: 'Derived from the Hershey vector fonts (public domain, A. V. Hershey, 1967), via the EMS SVG fonts.',
  relief: 'Relief SingleLine — SIL Open Font License 1.1 — (c) The Relief SingleLine Project Authors.',
  ems: 'EMS fonts — SIL Open Font License 1.1 — Sheldon B. Michaels / Windell H. Oskay (Evil Mad Scientist).',
};

const keys = readdirSync(new URL('data/json/', root)).filter((f) => f.endsWith('.json') && f !== 'index.json').map((f) => f.slice(0, -5)).sort();
for (const key of keys) {
  const data = JSON.parse(readFileSync(new URL(`data/json/${key}.json`, root), 'utf8'));
  const woff2 = readFileSync(new URL(`data/metrics/${key}.woff2`, root)).toString('base64');
  const lic = key.startsWith('hershey') ? LICENSE.hershey : key === 'relief' ? LICENSE.relief : LICENSE.ems;
  writeFileSync(new URL(`${key}.ts`, out), `// Generated by scripts/generate.mjs — do not edit.
// ${data.name}. ${lic}
import type { InkHand } from '../types';

const hand: InkHand = ${JSON.stringify({ key, ...data, metrics: `data:font/woff2;base64,${woff2}` })};
export default hand;
`);
}

const camel = (k) => k.replace(/-(\w)/g, (_, c) => c.toUpperCase());
writeFileSync(new URL('src/index.ts', root), `// Generated by scripts/generate.mjs — do not edit.
export type { InkHand } from './types';
import type { InkHand } from './types';

/** Every bundled hand, loaded on demand (each is its own chunk). */
export const hands = {
${keys.map((k) => `  ${JSON.stringify(k)}: () => import('./hands/${k}').then((m) => m.default),`).join('\n')}
} satisfies Record<string, () => Promise<InkHand>>;

export type HandKey = keyof typeof hands;
export const handKeys = Object.keys(hands) as HandKey[];

/** Display names, for pickers. */
export const handNames: Record<HandKey, string> = {
${keys.map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(JSON.parse(readFileSync(new URL(`data/json/${k}.json`, root), 'utf8')).name.replace(/^EMS /, '').replace(/ SVG$/, ''))},`).join('\n')}
};
`);
console.log(`generated ${keys.length} hands`);
